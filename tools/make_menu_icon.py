#!/usr/bin/env python3
"""Builds the reNut pause tab's icon (gpu/render/settings_icon.cpp) from a PNG.

The tab is the pause screen's unused map tab, whose icon texture,
aid_texture_banjox_ui_pausemenuicons_townmap (96x96, BC2, one level, in the
common bundle Bundle/4f/685374), nothing else shows. reNut swaps its blocks
for these as the texture uploads, as it does the title logo. The PNG (any
square size) is scaled to 96x96, premultiplied, encoded to BC2 with
make_title_logo.py's encoder and written, zstd-compressed, as a C++ byte
array.

usage: python make_menu_icon.py <icon.png> <out.inc>
       python make_menu_icon.py --hash-original
         (the XXH3 of the game's townmap icon blocks, row after row, each
          row's seeded with the last: what settings_icon.cpp recognises)
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import make_title_logo as logo  # noqa: E402

SIZE = 96
BLOCKS = SIZE // 4
ASSET = "aid_texture_banjox_ui_pausemenuicons_townmap\\"


def original_blocks():
    import dump_shaders as ds

    bundle = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "Bundle", "4f", "685374")
    for _, caff in ds.iter_caffs(bundle):
        for i in range(1, len(caff.files) + 1):
            a = caff.files[i - 1]["asset"]
            name = caff.symbols[a - 1].split(",")[0] if 0 < a <= len(caff.symbols) else ""
            if ASSET in name and caff.section_name(i) == ".texturegpu":
                raw = caff.read_file(i)
                rows = []
                for y in range(BLOCKS):
                    row = bytearray()
                    for x in range(BLOCKS):
                        o = logo_tiled(x, y)
                        blk = bytearray(raw[o:o + 16])
                        blk[0::2], blk[1::2] = blk[1::2], blk[0::2]  # 8in16
                        row += blk
                    rows.append(bytes(row))
                return rows
    raise SystemExit(ASSET.rstrip("\\") + " not found")


def logo_tiled(x, y):
    # XGAddress2DTiledOffset for 16-byte blocks (texture_layout.cpp TiledOffset2D).
    pitch, l2 = BLOCKS, 4
    tpr = ((pitch + 31) & ~31) >> 5
    sh = l2 + 6
    tile = (((x >> 5) + (y >> 5) * tpr) << sh) & 0x1FFFFFFF
    micro = (((x & 7) + ((y << 2) & 0x18)) << sh) >> 6
    a = 2 * (tile + (micro & ~0xF)) + (micro & 0xF) + (((y >> 3) & 1) << sh) + ((y & 1) << 4)
    b = ((2 * ((x >> 3) + ((y >> 2) & 2))) & 6) + ((y >> 4) & 1)
    return ((b & 1) << 11) + (((a >> 6) & 7) << 8) + ((b & ~1) << 5) + ((a & ~0x1FF) << 3) + (a & 0x3F)


def scale(path):
    from PIL import Image
    im = Image.open(path).convert("RGBA")
    a = np.asarray(im, dtype=np.float32) / 255.0
    pre = a.copy()
    pre[..., :3] *= pre[..., 3:4]
    channels = [Image.fromarray(pre[..., c]).resize((SIZE, SIZE), Image.LANCZOS) for c in range(4)]
    out = np.stack([np.asarray(c, dtype=np.float32) for c in channels], -1).clip(0.0, 1.0)
    alpha = out[..., 3:4]
    rgb = np.where(alpha > 1e-4, out[..., :3] / np.maximum(alpha, 1e-4), 0.0).clip(0.0, 1.0)
    return rgb, alpha[..., 0]


def main():
    if sys.argv[1:] == ["--hash-original"]:
        import xxhash
        h = 0
        for row in original_blocks():
            h = xxhash.xxh3_64_intdigest(row, seed=h)
        print("0x%016XULL" % h)
        return
    import zstandard
    rgb, alpha = scale(sys.argv[1])
    # make_title_logo's encoder works on its module's block grid.
    logo.BW, logo.BH = BLOCKS, BLOCKS
    data = logo.encode(rgb, alpha)
    packed = zstandard.ZstdCompressor(level=19).compress(data)
    with open(sys.argv[2], "w", newline="\n") as f:
        f.write("// Generated by tools/make_menu_icon.py from %s: the reNut pause tab's icon,\n"
                "// 96x96 BC2 blocks, zstd-compressed.\n" % sys.argv[1].replace("\\", "/").rsplit("/", 1)[-1])
        f.write("constexpr size_t kSettingsIconBytes = %d;\n" % len(data))
        f.write("constexpr unsigned char kSettingsIconZstd[] = {\n")
        for i in range(0, len(packed), 20):
            f.write("    " + ", ".join("0x%02X" % b for b in packed[i:i + 20]) + ",\n")
        f.write("};\n")
    print("%d bytes of blocks, %d compressed" % (len(data), len(packed)))


if __name__ == "__main__":
    main()
